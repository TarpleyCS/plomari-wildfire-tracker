create or replace function truth.validate_material_change_chain()
returns trigger
language plpgsql
security invoker
set search_path = ''
as $$
declare
  expected_previous bigint;
  target_as_of timestamptz;
  invalid_evidence_event boolean;
  basis_event_public_id uuid;
begin
  select previous_snapshot_cursor, as_of
    into expected_previous, target_as_of
  from truth.snapshots
  where cursor = new.to_snapshot_cursor and incident_id = new.incident_id;

  if not found or new.from_snapshot_cursor is distinct from expected_previous then
    raise exception 'material change must compare a snapshot with its actual predecessor'
      using errcode = '23514';
  end if;
  if new.calculated_at < target_as_of then
    raise exception 'material change time cannot precede its target snapshot' using errcode = '23514';
  end if;
  if not new.basis_event_cursor = any(new.evidence_event_cursors) then
    raise exception 'material change evidence events must include its basis event' using errcode = '23514';
  end if;
  if new.basis_evidence_id is not null and not exists (
    select 1
    from truth.evidence as evidence
    where evidence.id = new.basis_evidence_id
      and evidence.incident_id = new.incident_id
      and evidence.event_cursor = new.basis_event_cursor
  ) then
    raise exception 'material change basis evidence must support its basis event' using errcode = '23514';
  end if;
  select exists (
    select 1
    from unnest(new.evidence_event_cursors) as evidence_cursor
    left join truth.events as e
      on e.cursor = evidence_cursor and e.incident_id = new.incident_id
    where e.cursor is null
  ) into invalid_evidence_event;
  if invalid_evidence_event then
    raise exception 'material change evidence events must belong to the same incident' using errcode = '23514';
  end if;
  if new.protective_action is not null then
    select public_id::uuid into basis_event_public_id
    from truth.events
    where cursor = new.basis_event_cursor and incident_id = new.incident_id;
    if new.protective_action->>'sourceEventId' <> basis_event_public_id::text then
      raise exception 'protective action source event must equal the basis event' using errcode = '23514';
    end if;
  end if;
  return new;
end;
$$;

