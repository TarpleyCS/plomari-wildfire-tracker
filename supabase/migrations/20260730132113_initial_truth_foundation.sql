create or replace function core.validate_collection_target_revision_chain()
returns trigger
language plpgsql
security invoker
set search_path = ''
as $$
declare
  prior_version bigint;
  prior_effective_at timestamptz;
  prior_recorded_at timestamptz;
  target_incident_id bigint;
begin
  select incident_id into target_incident_id
  from core.collection_targets
  where id = new.collection_target_id;

  if target_incident_id is distinct from new.incident_id then
    raise exception 'collection target revision incident must match target identity' using errcode = '23514';
  end if;

  if new.previous_revision_id is null then
    if new.version_no <> 1 then
      raise exception 'first collection target revision must use version_no 1' using errcode = '23514';
    end if;
    return new;
  end if;

  select version_no, effective_at, recorded_at
    into prior_version, prior_effective_at, prior_recorded_at
  from core.collection_target_revisions
  where id = new.previous_revision_id
    and collection_target_id = new.collection_target_id;

  if prior_version is null or new.version_no <> prior_version + 1 then
    raise exception 'collection target revision must extend the previous target revision by one'
      using errcode = '23514';
  end if;
  if new.effective_at < prior_effective_at or new.recorded_at < prior_recorded_at then
    raise exception 'collection target revision times must be monotonic' using errcode = '23514';
  end if;
  return new;
end;
$$;

