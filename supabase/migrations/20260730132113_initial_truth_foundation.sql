create or replace function ingest.validate_run_lease()
returns trigger
language plpgsql
security invoker
set search_path = ''
as $$
begin
  if new.status <> 'running' or new.finished_at is not null then
    raise exception 'ingestion runs must be inserted in running state' using errcode = '23514';
  end if;
  if not exists (
    select 1
    from ingest.jobs as j
    where j.id = new.job_id
      and j.status = 'running'
      and j.lease_token = new.lease_token
      and j.lease_owner = new.lease_owner
      and j.lease_expires_at > now()
      and j.attempt_count = new.attempt_no
  ) then
    raise exception 'ingestion run requires the active job lease' using errcode = '55000';
  end if;
  return new;
end;
$$;

