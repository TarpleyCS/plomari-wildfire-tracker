create or replace function truth.finish_outbox_message(
  p_cursor bigint,
  p_lease_token uuid,
  p_worker_id text,
  p_outcome text,
  p_error jsonb default null,
  p_retry_at timestamptz default now()
)
returns boolean
language sql
volatile
security definer
set search_path = ''
as $$
  with finished as (
    update truth.outbox as o
    set status = case
          when p_outcome = 'retry' and o.attempt_count < o.max_attempts then 'retry'
          when p_outcome = 'retry' then 'dead'
          else p_outcome
        end,
        available_at = case when p_outcome = 'retry' then p_retry_at else o.available_at end,
        published_at = case when p_outcome = 'published' then now() else null end,
        lease_token = null,
        lease_owner = null,
        lease_expires_at = null,
        last_error = p_error,
        updated_at = now()
    where o.cursor = p_cursor
      and o.status = 'publishing'
      and o.lease_token = p_lease_token
      and o.lease_owner = p_worker_id
      and o.lease_expires_at > now()
      and p_outcome in ('published', 'retry', 'failed', 'dead')
      and (
        p_outcome <> 'published'
        or truth.publication_subject_is_dispatchable(
          o.publication_cursor,
          o.incident_id,
          o.event_cursor,
          o.material_change_cursor,
          now()
        )
      )
      and btrim(p_worker_id) <> ''
    returning true as finished
  )
  select coalesce((select finished from finished), false);
$$;

