create or replace function ingest.claim_collection_job(
  p_worker_id text,
  p_lease_for interval default interval '2 minutes'
)
returns setof ingest.jobs
language sql
volatile
security definer
set search_path = ''
as $$
  with exhausted as (
    update ingest.jobs as j
    set status = 'failed',
        completed_at = now(),
        lease_token = null,
        lease_owner = null,
        lease_expires_at = null,
        last_error = jsonb_build_object('class', 'lease_expired', 'terminal', true),
        updated_at = now()
    where j.status = 'running'
      and j.lease_expires_at <= now()
      and j.attempt_count >= j.max_attempts
    returning j.id
  ), invalidated as (
    update ingest.jobs as j
    set status = 'cancelled',
        completed_at = now(),
        lease_token = null,
        lease_owner = null,
        lease_expires_at = null,
        last_error = jsonb_build_object(
          'class', 'collection_configuration_disabled',
          'terminal', true
        ),
        updated_at = now()
    where (
        j.status in ('pending', 'retry')
        or (j.status = 'running' and j.lease_expires_at <= now())
      )
      and not (
        j.status = 'running'
        and j.lease_expires_at <= now()
        and j.attempt_count >= j.max_attempts
      )
      and not exists (
        select 1
        from core.sources as source
        join core.endpoints as endpoint
          on endpoint.id = j.endpoint_id and endpoint.source_id = source.id
        join ingest.endpoint_state as endpoint_state
          on endpoint_state.endpoint_id = endpoint.id
        join core.adapter_releases as adapter
          on adapter.id = j.adapter_release_id and adapter.source_id = source.id
        join ingest.adapter_release_state as adapter_state
          on adapter_state.adapter_release_id = adapter.id
        join core.collection_targets as target
          on target.id = j.collection_target_id
          and target.endpoint_id = endpoint.id
          and target.source_id = source.id
        join core.collection_target_revisions as revision
          on revision.id = j.collection_target_revision_id
          and revision.collection_target_id = target.id
          and revision.endpoint_id = endpoint.id
        where source.id = j.source_id
          and source.enabled
          and endpoint_state.enabled
          and endpoint_state.paused_reason is null
          and adapter_state.enabled
          and adapter_state.retired_at is null
          and target.enabled
          and revision.enabled
          and revision.effective_at <= now()
          and not exists (
            select 1
            from core.collection_target_revisions as newer_revision
            where newer_revision.collection_target_id = revision.collection_target_id
              and newer_revision.effective_at <= now()
              and (
                newer_revision.effective_at > revision.effective_at
                or (
                  newer_revision.effective_at = revision.effective_at
                  and newer_revision.version_no > revision.version_no
                )
              )
          )
      )
    returning j.id
  ), candidate as (
    select j.id
    from ingest.jobs as j
    join core.sources as source on source.id = j.source_id and source.enabled
    join core.endpoints as endpoint
      on endpoint.id = j.endpoint_id and endpoint.source_id = source.id
    join ingest.endpoint_state as endpoint_state
      on endpoint_state.endpoint_id = endpoint.id
      and endpoint_state.enabled
      and endpoint_state.paused_reason is null
    join core.adapter_releases as adapter
      on adapter.id = j.adapter_release_id and adapter.source_id = source.id
    join ingest.adapter_release_state as adapter_state
      on adapter_state.adapter_release_id = adapter.id
      and adapter_state.enabled
      and adapter_state.retired_at is null
    join core.collection_targets as target
      on target.id = j.collection_target_id
      and target.endpoint_id = endpoint.id
      and target.source_id = source.id
      and target.enabled
    join core.collection_target_revisions as revision
      on revision.id = j.collection_target_revision_id
      and revision.collection_target_id = target.id
      and revision.endpoint_id = endpoint.id
      and revision.enabled
      and revision.effective_at <= now()
    where (
        (j.status in ('pending', 'retry') and j.available_at <= now())
        or (j.status = 'running' and j.lease_expires_at <= now())
      )
      and j.attempt_count < j.max_attempts
      and not exists (
        select 1
        from core.collection_target_revisions as newer_revision
        where newer_revision.collection_target_id = revision.collection_target_id
          and newer_revision.effective_at <= now()
          and (
            newer_revision.effective_at > revision.effective_at
            or (
              newer_revision.effective_at = revision.effective_at
              and newer_revision.version_no > revision.version_no
            )
          )
      )
      and p_lease_for > interval '0 seconds'
      and btrim(p_worker_id) <> ''
    order by j.priority desc, j.available_at, j.id
    for update of j skip locked
    limit 1
  )
  update ingest.jobs as j
  set status = 'running',
      attempt_count = j.attempt_count + 1,
      lease_token = gen_random_uuid(),
      lease_owner = p_worker_id,
      lease_expires_at = now() + p_lease_for,
      claimed_at = now(),
      updated_at = now()
  from candidate
  where j.id = candidate.id
  returning j.*;
$$;

