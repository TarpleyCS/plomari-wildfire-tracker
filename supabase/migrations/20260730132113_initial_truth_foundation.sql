-- Capability roles are deliberately NOLOGIN and NOBYPASSRLS. Production login
-- roles are provisioned out of band and receive exactly one capability role;
-- no password or deploy-time credential belongs in schema history.
do $roles$
declare
  role_name text;
  role_is_superuser boolean;
  role_can_replicate boolean;
  role_bypasses_rls boolean;
begin
  foreach role_name in array array[
    'firewatch_catalog_admin',
    'firewatch_collector',
    'firewatch_reconciler',
    'firewatch_publisher',
    'firewatch_dispatcher'
  ]
  loop
    if not exists (select 1 from pg_roles where rolname = role_name) then
      execute format(
        'create role %I with nologin noinherit nosuperuser nocreatedb nocreaterole noreplication nobypassrls',
        role_name
      );
    else
      select rolsuper, rolreplication, rolbypassrls
        into role_is_superuser, role_can_replicate, role_bypasses_rls
      from pg_roles
      where rolname = role_name;

      if role_is_superuser or role_can_replicate or role_bypasses_rls then
        raise exception 'existing capability role % has unsafe privileged attributes', role_name
          using errcode = '42501';
      end if;
    end if;
    -- A Supabase migration owner has CREATEROLE but is intentionally not a
    -- superuser. Reassert only attributes CREATEROLE may alter; the privileged
    -- flags above are validated fail-closed instead.
    execute format(
      'alter role %I with nologin noinherit nocreatedb nocreaterole',
      role_name
    );
  end loop;
end;
$roles$;

