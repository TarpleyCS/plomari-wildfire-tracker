-- The catalog lifecycle is editorial/operational metadata. An official fire
-- status exists only when a current, published authority-backed transition can
-- still pass the evidence gates at read time.
create or replace function truth.current_official_status(p_incident_id bigint)
returns text
language sql
stable
security definer
set search_path = ''
as $$
  select event.payload->>'toStatus'
  from core.incidents as incident
  join truth.events as event
    on event.incident_id = incident.id
    and event.event_type = 'official_status_transition'
    and event.visibility = 'public'
  join truth.publications as publication
    on publication.event_cursor = event.cursor
  where incident.id = p_incident_id
    and incident.visibility = 'public'
    and truth.publication_subject_is_current(
      publication.cursor, incident.id, event.cursor, null, null, now()
    )
  order by
    coalesce(event.last_effective_at, event.first_effective_at, publication.action_at) desc,
    publication.cursor desc
  limit 1;
$$;

revoke execute on function truth.current_official_status(bigint)
