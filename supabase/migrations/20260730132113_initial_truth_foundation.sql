create or replace function truth.event_details_are_valid(
  p_event_type text,
  p_details jsonb
)
returns boolean
language plpgsql
immutable
strict
security invoker
set search_path = ''
as $$
declare
  allowed_keys text[];
  required_keys text[];
begin
  if jsonb_typeof(p_details) <> 'object' then
    return false;
  end if;

  case p_event_type
    when 'protective_instruction' then
      allowed_keys := array[
        'instructionKind', 'actionText', 'originalLanguage',
        'originExplicit', 'destinationExplicit', 'affectedAreaExplicit'
      ];
      required_keys := allowed_keys;
      if p_details->>'instructionKind' not in ('readiness', 'evacuate', 'shelter', 'cancel', 'all_clear')
        or coalesce(btrim(p_details->>'actionText'), '') = ''
        or coalesce(btrim(p_details->>'originalLanguage'), '') = ''
        or jsonb_typeof(p_details->'originExplicit') <> 'boolean'
        or jsonb_typeof(p_details->'destinationExplicit') <> 'boolean'
        or jsonb_typeof(p_details->'affectedAreaExplicit') <> 'boolean'
      then return false; end if;
    when 'official_status_transition' then
      allowed_keys := array['fromStatus', 'toStatus'];
      required_keys := allowed_keys;
      if p_details->>'fromStatus' not in ('in_progress', 'partial_control', 'full_control', 'ended', 'unknown')
        or p_details->>'toStatus' not in ('in_progress', 'partial_control', 'full_control', 'ended', 'unknown')
      then return false; end if;
    when 'thermal_detection' then
      allowed_keys := array['product', 'satellite', 'frpMw', 'confidence', 'scanKm', 'trackKm'];
      required_keys := allowed_keys;
      if coalesce(btrim(p_details->>'product'), '') = ''
        or coalesce(btrim(p_details->>'satellite'), '') = ''
        or jsonb_typeof(p_details->'confidence') not in ('string', 'number')
        or jsonb_typeof(p_details->'frpMw') not in ('number', 'null')
        or jsonb_typeof(p_details->'scanKm') not in ('number', 'null')
        or jsonb_typeof(p_details->'trackKm') not in ('number', 'null')
      then return false; end if;
    when 'thermal_pass' then
      allowed_keys := array['product', 'satellite', 'passStart', 'detectionCount'];
      required_keys := allowed_keys;
      if coalesce(btrim(p_details->>'product'), '') = ''
        or coalesce(btrim(p_details->>'satellite'), '') = ''
        or coalesce(btrim(p_details->>'passStart'), '') = ''
        or jsonb_typeof(p_details->'detectionCount') <> 'number'
      then return false; end if;
    when 'road_condition' then
      allowed_keys := array['roadName', 'state', 'direction'];
      required_keys := allowed_keys;
      if coalesce(btrim(p_details->>'roadName'), '') = ''
        or p_details->>'state' not in ('open', 'closed', 'restricted', 'unknown')
        or jsonb_typeof(p_details->'direction') not in ('string', 'null')
      then return false; end if;
    when 'settlement_threat' then
      allowed_keys := array['settlementName', 'reportedRelationship'];
      required_keys := allowed_keys;
      if coalesce(btrim(p_details->>'settlementName'), '') = ''
        or coalesce(btrim(p_details->>'reportedRelationship'), '') = ''
      then return false; end if;
    when 'smoke_observation' then
      allowed_keys := array['basis', 'description', 'modelVersion', 'inputVersion'];
      required_keys := case when p_details->>'basis' = 'modeled'
        then allowed_keys else array['basis', 'description'] end;
      if p_details->>'basis' not in ('observed', 'modeled')
        or coalesce(btrim(p_details->>'description'), '') = ''
        or (p_details->>'basis' = 'observed' and (p_details ? 'modelVersion' or p_details ? 'inputVersion'))
        or (p_details->>'basis' = 'modeled' and (
          coalesce(btrim(p_details->>'modelVersion'), '') = ''
          or coalesce(btrim(p_details->>'inputVersion'), '') = ''
        ))
      then return false; end if;
    when 'weather_observation' then
      allowed_keys := array[
        'basis', 'stationOrModel', 'windSpeedKmh', 'windGustKmh', 'windDirectionDeg'
      ];
      required_keys := allowed_keys;
      if p_details->>'basis' not in ('measured', 'modeled')
        or coalesce(btrim(p_details->>'stationOrModel'), '') = ''
        or jsonb_typeof(p_details->'windSpeedKmh') not in ('number', 'null')
        or jsonb_typeof(p_details->'windGustKmh') not in ('number', 'null')
        or jsonb_typeof(p_details->'windDirectionDeg') not in ('number', 'null')
      then return false; end if;
    when 'weather_model_change' then
      allowed_keys := array['model', 'modelRunAt', 'changeCode'];
      required_keys := allowed_keys;
      if coalesce(btrim(p_details->>'model'), '') = ''
        or coalesce(btrim(p_details->>'modelRunAt'), '') = ''
        or coalesce(btrim(p_details->>'changeCode'), '') = ''
      then return false; end if;
    when 'response_update' then
      allowed_keys := array['resourceSummary'];
      required_keys := allowed_keys;
      if coalesce(btrim(p_details->>'resourceSummary'), '') = '' then return false; end if;
    when 'source_correction' then
      allowed_keys := array['priorSourceItemId', 'newSourceItemId'];
      required_keys := allowed_keys;
      if p_details->>'priorSourceItemId' !~ '^[0-9a-f]{8}-[0-9a-f]{4}-7[0-9a-f]{3}-[89ab][0-9a-f]{3}-[0-9a-f]{12}$'
        or p_details->>'newSourceItemId' !~ '^[0-9a-f]{8}-[0-9a-f]{4}-7[0-9a-f]{3}-[89ab][0-9a-f]{3}-[0-9a-f]{12}$'
      then return false; end if;
    else
      return false;
  end case;

  return p_details ?& required_keys
    and not exists (
      select 1
      from jsonb_object_keys(p_details) as supplied(key)
      where not supplied.key = any(allowed_keys)
    );
end;
$$;

