create or replace function truth.validate_publication_chain()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  prior truth.publications%rowtype;
  subject_event_type text;
  subject_claim_type text;
  subject_basis_event_cursor bigint;
  subject_recorded_at timestamptz;
begin
  if new.recorded_at is distinct from now() then
    raise exception 'publication recording time is database assigned'
      using errcode = '23514';
  end if;
  if new.action_at > new.recorded_at then
    raise exception 'publication action time cannot be later than its recording time'
      using errcode = '23514';
  end if;

  if new.previous_publication_cursor is null then
    if new.action <> 'publish' then
      raise exception 'first publication action must publish its subject' using errcode = '23514';
    end if;
  else
    select * into prior
    from truth.publications
    where cursor = new.previous_publication_cursor;

    if not found
      or prior.incident_id <> new.incident_id
      or prior.event_cursor is distinct from new.event_cursor
      or prior.snapshot_cursor is distinct from new.snapshot_cursor
      or prior.material_change_cursor is distinct from new.material_change_cursor
    then
      raise exception 'publication action must extend the same subject chain' using errcode = '23514';
    end if;
    if prior.action = new.action then
      raise exception 'publication actions must alternate between publish and retract' using errcode = '23514';
    end if;
    if new.action_at < prior.action_at or new.recorded_at < prior.recorded_at then
      raise exception 'publication action times must be monotonic' using errcode = '23514';
    end if;
  end if;

  if new.action = 'publish' and new.event_cursor is not null then
    subject_basis_event_cursor := new.event_cursor;
    select event_type, recorded_at into subject_claim_type, subject_recorded_at
    from truth.events
    where cursor = new.event_cursor and incident_id = new.incident_id;
  elsif new.action = 'publish' and new.snapshot_cursor is not null then
    select basis_event_cursor, created_at
      into subject_basis_event_cursor, subject_recorded_at
    from truth.snapshots
    where cursor = new.snapshot_cursor and incident_id = new.incident_id;
  elsif new.action = 'publish' and new.material_change_cursor is not null then
    select change_type, basis_event_cursor, greatest(calculated_at, created_at)
      into subject_claim_type, subject_basis_event_cursor, subject_recorded_at
    from truth.material_changes
    where cursor = new.material_change_cursor and incident_id = new.incident_id;
  end if;

  if new.action = 'publish' then
    if subject_recorded_at is null or subject_recorded_at > new.action_at then
      raise exception 'publication action cannot predate its database-recorded subject'
        using errcode = '23514';
    end if;

    select event_type into subject_event_type
    from truth.events
    where cursor = subject_basis_event_cursor and incident_id = new.incident_id;

    if subject_event_type is null then
      raise exception 'publication subject lacks a same-incident basis event'
        using errcode = '23514';
    end if;

    if subject_event_type = 'protective_instruction'
      or subject_claim_type = 'protective_instruction'
    then
      if not truth.protective_event_has_publishable_authority(
        subject_basis_event_cursor, new.incident_id, new.action_at, new.recorded_at
      ) then
        raise exception 'protective instruction lacks accepted authoritative provenance'
          using errcode = '23514';
      end if;
    elsif subject_event_type = 'official_status_transition'
      or subject_claim_type = 'official_status_transition'
    then
      if not truth.official_status_event_has_publishable_authority(
        subject_basis_event_cursor, new.incident_id, new.action_at, new.recorded_at
      ) then
        raise exception 'official status transition lacks accepted authoritative provenance'
          using errcode = '23514';
      end if;
    end if;

    if not truth.event_has_publishable_evidence(
      subject_basis_event_cursor, new.incident_id, new.action_at, new.recorded_at
    ) then
      raise exception 'publication subject lacks accepted evidence-backed provenance'
        using errcode = '23514';
    end if;
  end if;
  return new;
end;
$$;

