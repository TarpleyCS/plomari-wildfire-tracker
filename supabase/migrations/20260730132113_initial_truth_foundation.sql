create or replace function truth.validate_outbox_enqueue()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  publication_public_id uuid;
  publication_action_at timestamptz;
  publication_recorded_at timestamptz;
  subject_kind text;
  subject_public_id uuid;
  routing_type text;
  expected_topic text;
  expected_partition_key text;
  expected_payload jsonb;
begin
  if new.status <> 'pending'
    or new.attempt_count <> 0
    or new.lease_token is not null
    or new.lease_owner is not null
    or new.lease_expires_at is not null
    or new.published_at is not null
    or new.last_error is not null
  then
    raise exception 'outbox messages must be inserted in pristine pending state'
      using errcode = '23514';
  end if;

  select p.public_id::uuid, p.action_at, p.recorded_at
    into publication_public_id, publication_action_at, publication_recorded_at
  from truth.publications as p
  where p.cursor = new.publication_cursor
    and p.incident_id = new.incident_id;

  if not found
    or new.created_at < publication_action_at
    or new.created_at < publication_recorded_at
    or new.created_at is distinct from now()
    or new.available_at < new.created_at
    or not truth.publication_subject_is_dispatchable(
      new.publication_cursor,
      new.incident_id,
      new.event_cursor,
      new.material_change_cursor,
      new.created_at
    )
  then
    raise exception 'outbox enqueue requires the current authorized publish action'
      using errcode = '23514';
  end if;

  if new.event_cursor is not null then
    subject_kind := 'event';
    select e.public_id::uuid, e.event_type
      into subject_public_id, routing_type
    from truth.events as e
    where e.cursor = new.event_cursor and e.incident_id = new.incident_id;
  else
    subject_kind := 'material_change';
    select change.public_id::uuid, change.change_type
      into subject_public_id, routing_type
    from truth.material_changes as change
    where change.cursor = new.material_change_cursor
      and change.incident_id = new.incident_id;
  end if;

  expected_payload := jsonb_build_object(
    'contractVersion', '1.1.0',
    'publicationId', publication_public_id::text,
    'subjectKind', subject_kind,
    'subjectId', subject_public_id::text
  );
  if new.payload <> expected_payload then
    raise exception 'outbox payload must be the exact publication identifier envelope'
      using errcode = '23514';
  end if;

  if routing_type in ('road_condition', 'settlement_threat') then
    raise exception 'notification route lacks a claim-specific authority gate'
      using errcode = '23514';
  end if;

  expected_topic := case routing_type
    when 'incident_created' then 'incident.created'
    when 'protective_instruction' then 'incident.protective'
    when 'official_status_transition' then 'incident.status'
    when 'thermal_detection' then 'incident.thermal_detection'
    when 'thermal_pass' then 'incident.thermal_pass'
    when 'smoke_observation' then 'incident.smoke'
    when 'weather_observation' then 'incident.weather'
    when 'weather_model_change' then 'incident.weather_model_change'
    when 'response_update' then 'incident.response'
    when 'source_correction' then 'incident.source_correction'
    when 'source_stale' then 'incident.source_stale'
    when 'all_sources_unavailable' then 'incident.sources_unavailable'
    else null
  end;
  select incident.public_id::uuid::text into expected_partition_key
  from core.incidents as incident
  where incident.id = new.incident_id;

  if expected_topic is null
    or new.topic <> expected_topic
    or new.partition_key <> expected_partition_key
  then
    raise exception 'outbox route must match the publication subject and incident'
      using errcode = '23514';
  end if;
  return new;
end;
$$;

