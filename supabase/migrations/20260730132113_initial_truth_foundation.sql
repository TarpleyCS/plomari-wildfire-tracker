create or replace function ingest.validate_source_revision_chain()
returns trigger
language plpgsql
security invoker
set search_path = ''
as $$
declare
  prior_revision bigint;
begin
  if new.previous_revision_id is null then
    if new.revision_no <> 1 then
      raise exception 'first source revision must use revision_no 1' using errcode = '23514';
    end if;
    return new;
  end if;

  select revision_no into prior_revision
  from ingest.source_revisions
  where id = new.previous_revision_id
    and source_id = new.source_id
    and source_record_key = new.source_record_key;

  if prior_revision is null or new.revision_no <> prior_revision + 1 then
    raise exception 'source revision must extend the previous record revision by one' using errcode = '23514';
  end if;
  return new;
end;
$$;

