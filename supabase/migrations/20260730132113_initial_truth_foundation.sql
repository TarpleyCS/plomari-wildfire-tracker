create or replace function core.validate_aoi_version_chain()
returns trigger
language plpgsql
security invoker
set search_path = ''
as $$
declare
  prior_version bigint;
  prior_effective_at timestamptz;
  prior_recorded_at timestamptz;
begin
  if new.previous_version_id is null then
    if new.version_no <> 1 then
      raise exception 'first AOI version must use version_no 1' using errcode = '23514';
    end if;
    return new;
  end if;

  select version_no, effective_at, recorded_at
    into prior_version, prior_effective_at, prior_recorded_at
  from core.aoi_versions
  where id = new.previous_version_id and incident_id = new.incident_id;

  if prior_version is null or new.version_no <> prior_version + 1 then
    raise exception 'AOI version must extend the previous incident version by one' using errcode = '23514';
  end if;
  if new.effective_at < prior_effective_at or new.recorded_at < prior_recorded_at then
    raise exception 'AOI version times must be monotonic' using errcode = '23514';
  end if;
  return new;
end;
$$;

revoke execute on function core.validate_aoi_version_chain() from public, anon, authenticated;

