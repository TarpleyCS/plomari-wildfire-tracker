create or replace function truth.claim_outbox_message(
  p_worker_id text,
  p_lease_for interval default interval '2 minutes'
)
returns setof truth.outbox
language sql
volatile
security definer
set search_path = ''
as $$
  with exhausted as (
    update truth.outbox as o
    set status = 'dead',
        lease_token = null,
        lease_owner = null,
        lease_expires_at = null,
        last_error = jsonb_build_object('class', 'lease_expired', 'terminal', true),
        updated_at = now()
    where o.status = 'publishing'
      and o.lease_expires_at <= now()
      and o.attempt_count >= o.max_attempts
    returning o.cursor
  ), invalidated as (
    update truth.outbox as o
    set status = 'dead',
        lease_token = null,
        lease_owner = null,
        lease_expires_at = null,
        last_error = jsonb_build_object(
          'class', 'publication_no_longer_dispatchable',
          'terminal', true
        ),
        updated_at = now()
    where o.status in ('pending', 'retry', 'publishing')
      and not (
        o.status = 'publishing'
        and o.lease_expires_at <= now()
        and o.attempt_count >= o.max_attempts
      )
      and not truth.publication_subject_is_dispatchable(
        o.publication_cursor,
        o.incident_id,
        o.event_cursor,
        o.material_change_cursor,
        now()
      )
    returning o.cursor
  ), candidate as (
    select o.cursor
    from truth.outbox as o
    where (
        (o.status in ('pending', 'retry') and o.available_at <= now())
        or (o.status = 'publishing' and o.lease_expires_at <= now())
      )
      and o.attempt_count < o.max_attempts
      and truth.publication_subject_is_dispatchable(
        o.publication_cursor,
        o.incident_id,
        o.event_cursor,
        o.material_change_cursor,
        now()
      )
      and p_lease_for > interval '0 seconds'
      and btrim(p_worker_id) <> ''
    order by o.available_at, o.cursor
    for update skip locked
    limit 1
  )
  update truth.outbox as o
  set status = 'publishing',
      attempt_count = o.attempt_count + 1,
      lease_token = gen_random_uuid(),
      lease_owner = p_worker_id,
      lease_expires_at = now() + p_lease_for,
      updated_at = now()
  from candidate
  where o.cursor = candidate.cursor
  returning o.*;
$$;

