      new.created_at := now(); new.updated_at := now();
    when 'truth.source_health' then
      new.checked_at := now(); new.created_at := now();
    else
      raise exception 'audit-clock trigger used on unsupported table' using errcode = '55000';
  end case;
  return new;
end;
$$;

