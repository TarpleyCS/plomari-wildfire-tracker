-- Once a live job has admitted a run, only the atomic run finalizer may release
-- that lease. Jobs whose lease already expired remain reclaimable by the queue.
create or replace function ingest.require_atomic_active_run_finish()
returns trigger
language plpgsql
security invoker
set search_path = ''
as $$
begin
  if old.status = 'running'
    and new.status <> 'running'
    and old.lease_expires_at > now()
    and exists (
      select 1
      from ingest.runs as active_run
      where active_run.job_id = old.id
        and active_run.status = 'running'
        and active_run.lease_token = old.lease_token
    )
  then
    raise exception 'active ingestion runs must be finalized atomically'
      using errcode = '55000';
  end if;
  return new;
end;
$$;

