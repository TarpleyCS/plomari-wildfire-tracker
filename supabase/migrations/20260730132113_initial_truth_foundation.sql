    where j.id = p_job_id
      and j.status = 'running'
      and j.lease_token = p_lease_token
      and j.lease_owner = p_worker_id
      and j.lease_expires_at > now()
      and p_outcome in ('succeeded', 'retry', 'failed', 'cancelled')
      and btrim(p_worker_id) <> ''
    returning true as finished
  )
  select coalesce((select finished from finished), false);
$$;

