-- Public reads and delivery claims fail closed if a once-publishable subject is
-- no longer the current evidence chain tip or its source authority has lapsed.
create or replace function truth.publication_subject_is_current(
  p_publication_cursor bigint,
  p_incident_id bigint,
  p_event_cursor bigint,
  p_snapshot_cursor bigint,
  p_material_change_cursor bigint,
  p_as_of timestamptz
)
returns boolean
language plpgsql
stable
security definer
set search_path = ''
as $$
declare
  publication truth.publications%rowtype;
  basis_event_cursor bigint;
  event_type text;
  claim_type text;
begin
  if p_as_of is null then
    return false;
  end if;

  select * into publication
  from truth.publications as p
  where p.cursor = p_publication_cursor
    and p.incident_id = p_incident_id;

  if not found
    or publication.action <> 'publish'
    or publication.event_cursor is distinct from p_event_cursor
    or publication.snapshot_cursor is distinct from p_snapshot_cursor
    or publication.material_change_cursor is distinct from p_material_change_cursor
    or publication.action_at > p_as_of
    or publication.recorded_at > p_as_of
    or exists (
      select 1
      from truth.publications as successor
      where successor.previous_publication_cursor = publication.cursor
        and successor.recorded_at <= p_as_of
    )
  then
    return false;
  end if;

  if p_event_cursor is not null then
    basis_event_cursor := p_event_cursor;
  elsif p_snapshot_cursor is not null then
    select snapshot.basis_event_cursor into basis_event_cursor
    from truth.snapshots as snapshot
    where snapshot.cursor = p_snapshot_cursor
      and snapshot.incident_id = p_incident_id;
  else
    select change.basis_event_cursor, change.change_type
      into basis_event_cursor, claim_type
    from truth.material_changes as change
    where change.cursor = p_material_change_cursor
      and change.incident_id = p_incident_id;
  end if;

  select event.event_type into event_type
  from truth.events as event
  where event.cursor = basis_event_cursor
    and event.incident_id = p_incident_id;

  if event_type is null
    or not truth.event_has_publishable_evidence(
      basis_event_cursor, p_incident_id, publication.action_at, p_as_of
    )
  then
    return false;
  end if;

  if event_type = 'protective_instruction' or claim_type = 'protective_instruction' then
    return truth.protective_event_has_publishable_authority(
      basis_event_cursor, p_incident_id, publication.action_at, p_as_of
    );
  end if;
  if event_type = 'official_status_transition'
    or claim_type = 'official_status_transition'
  then
    return truth.official_status_event_has_publishable_authority(
      basis_event_cursor, p_incident_id, publication.action_at, p_as_of
    );
  end if;
  return true;
end;
$$;

